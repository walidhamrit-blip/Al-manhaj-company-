/** English: 136.95 LYD — Arabic: 136.95 د.ل */
export function formatPrice(amount: number, lang: Language): string {
  const value = Number(amount || 0).toFixed(2);
  return lang === "ar" ? `${value} د.ل` : `${value} LYD`;
}

